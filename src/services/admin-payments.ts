/**
 * Platform-wide money views for the admin dashboard: every wallet movement,
 * every invoice and every Razorpay payment link, joined to their sponsor.
 *
 * Everything is stored in paise and converted at this boundary, so no screen
 * ever does its own /100.
 */
import { supabase } from '@/lib/supabase';
import { formatDate, formatDateShort } from '@/lib/transforms';
import { logAudit } from '@/services/admin-writes';

export interface PaymentRow {
  id: string;
  sponsorId: string;
  sponsorName: string;
  amountRupees: number;
  kind: string;
  reference: string;
  date: string;
  /** ISO date (yyyy-mm-dd) for range filtering. */
  isoDate: string;
}

export async function fetchAllPayments(): Promise<PaymentRow[]> {
  if (!supabase) return [];
  const { data, error } = await supabase
    .from('wallet_transactions')
    .select('*, sponsor:sponsors(name)')
    .order('created_at', { ascending: false })
    .limit(500);
  if (error || !data) return [];
  return (data as any[]).map((t) => ({
    id: t.id,
    sponsorId: t.sponsor_id,
    sponsorName: t.sponsor?.name ?? 'Unknown',
    amountRupees: Number(t.amount_paise || 0) / 100,
    kind: t.kind,
    reference: t.reference ?? '',
    date: formatDateShort(t.created_at),
    isoDate: String(t.created_at).slice(0, 10),
  }));
}

